-- Now we can wire the back-reference from page_view_events.contact_id.
do $$ begin
  if not exists (
    select 1 from information_schema.table_constraints
    where constraint_name = 'pve_contact_fk'
  ) then
    alter table public.page_view_events
      add constraint pve_contact_fk
      foreign key (contact_id) references public.ghl_contacts(id) on delete set null;
  end if;
end $$;

