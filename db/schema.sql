-- Convenience: rep daily metrics with derived rates (for /sales)
create or replace view public.v_sales_metrics_with_rates as
select
  date,
  rep_id,
  rep_name,
  intro_calls,
  live_intros,
  offers_made,
  closes,
  collected,
  case when intro_calls > 0 then live_intros::numeric / intro_calls else null end as show_rate,
  case when live_intros > 0 then offers_made::numeric / live_intros else null end as offer_rate,
  case when offers_made > 0 then closes::numeric / offers_made     else null end as close_rate,
  case when intro_calls > 0 then closes::numeric / intro_calls     else null end as call_to_close_rate,
  case when intro_calls > 0 then collected      / intro_calls      else null end as collected_per_call
from public.sales_metrics;

