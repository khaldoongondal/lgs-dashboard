-- ─────────────────────────────────────────────────────────────────────────────
-- 1. page_view_events — top of funnel, browser pixel fires this on every page
--    Stores fingerprint + fbclid + UTMs so anonymous sessions can later be
--    anchored to a known contact once they opt in.
-- ─────────────────────────────────────────────────────────────────────────────
create table if not exists public.page_view_events (
  id              bigint generated by default as identity primary key,
  event_id        text unique not null,
  event_name      text not null default 'PageView',
  event_time      timestamptz not null default now(),
  page_url        text,
  referrer        text,
  -- Identity signals
  fingerprint     text,                   -- ThumbmarkJS visitor ID (when wired)
  fbclid          text,
  fbp             text,
  fbc             text,
  -- UTMs
  utm_source      text,
  utm_medium      text,
  utm_campaign    text,
  utm_content     text,                   -- ad name
  utm_term        text,                   -- adset name
  -- Network
  client_ip       inet,
  user_agent      text,
  -- Linkage
  contact_id      bigint,                 -- set later when opt-in fires; FK below
  created_at      timestamptz not null default now()
);

create index if not exists idx_pve_event_time   on public.page_view_events (event_time desc);
create index if not exists idx_pve_fingerprint  on public.page_view_events (fingerprint);
create index if not exists idx_pve_fbclid       on public.page_view_events (fbclid);
create index if not exists idx_pve_utm_campaign on public.page_view_events (utm_campaign);
create index if not exists idx_pve_utm_content  on public.page_view_events (utm_content);
create index if not exists idx_pve_contact_id   on public.page_view_events (contact_id);

